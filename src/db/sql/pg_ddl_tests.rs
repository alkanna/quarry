//! Live tests of editing a PostgreSQL table's structure, run on every server named by QUARRY_TEST_POSTGRES and
//! QUARRY_TEST_POSTGRES13, and once through the PgBouncer. Each test makes its own schema in the shared `quarry_test`
//! database, so tests of one server run side by side.

use super::ddl::{self, Change, ColDef, Dv, IdxCol, IndexDef, IndexKind, Mode, Pos};
use super::structure::{Column, Structure};
use super::testing::{every_pg, live_pgbouncer, LivePg};
use super::{Db, Dialect};
use crate::db::{Msg, Res, UndoAction};

const TABLE_DDL: &str = "CREATE TABLE t (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name varchar(40) NOT NULL DEFAULT 'x', qty integer, note text); \
                         COMMENT ON COLUMN t.note IS 'free text'; CREATE INDEX t_name_idx ON t (name DESC, qty); \
                         INSERT INTO t (name, qty, note) VALUES ('a', 1, 'one'), ('b', 2, 'two'), ('c', 30, NULL)";

struct T<'a> {
    l: &'a LivePg,
    db: Db,
    pool: sqlx::PgPool,
    schema: String,
}

fn fixture<'a>(l: &'a LivePg, var: &str, tag: &str, ddl: &str) -> T<'a> {
    let db = l.quarry_test();
    let pool = l.fixture_pool();
    let schema = format!("pgddl_{tag}_{}", if var.ends_with("13") { "13" } else { "18" });
    l.qsql(&pool, &format!("DROP SCHEMA IF EXISTS {schema} CASCADE; CREATE SCHEMA {schema}; SET search_path = {schema}; {ddl}"));
    T { l, db, pool, schema }
}

impl Drop for T<'_> {
    fn drop(&mut self) {
        // The pool is gone with the test; a schema left behind by a failed one is dropped by the next run's fixture.
        let _ = self.l.w.rt.block_on(async { sqlx::raw_sql(&format!("DROP SCHEMA IF EXISTS {} CASCADE", self.schema)).execute(&self.pool).await });
    }
}

impl T<'_> {
    fn sql(&self, s: &str) {
        self.l.qsql(&self.pool, &format!("SET search_path = {}; {s}", self.schema));
    }

    fn one(&self, s: &str) -> String {
        self.l.qone(&self.pool, &format!("SET search_path = {}; {s}", self.schema))
    }

    fn structure(&self) -> Structure {
        self.l.w.sql_structure(9, self.db.clone(), self.schema.clone(), "t".into());
        let Msg::SqlStructure { res, .. } = self.l.next() else { panic!("expected SqlStructure") };
        res.unwrap()
    }

    fn col(&self, name: &str) -> Option<Column> {
        self.structure().columns.into_iter().find(|c| c.name == name)
    }

    fn def(&self, name: &str) -> ColDef {
        let st = self.structure();
        ColDef::in_table(&st, st.columns.iter().find(|c| c.name == name).unwrap()).unwrap()
    }

    fn plan(&self, changes: &[Change]) -> Result<ddl::Plan, String> {
        ddl::plan(Dialect::Postgres, &self.db.version, Mode::DEFAULT, "t", &self.structure(), changes)
    }

    fn run(&self, plan: ddl::Plan) -> (Res<String>, Option<UndoAction>) {
        let undo = plan.undo.ok().map(|mut u| {
            u.label = "changed the structure".into();
            u
        });
        self.l.w.pg_alter(1, self.db.clone(), self.schema.clone(), "t".into(), plan.steps, plan.expect.unwrap(), undo, false, "Changed the structure".into());
        let Msg::SqlAltered { res, undo, .. } = self.l.next() else { panic!("expected SqlAltered") };
        (res, undo)
    }

    fn apply(&self, changes: &[Change]) -> UndoAction {
        let plan = self.plan(changes).unwrap_or_else(|x| panic!("plan: {x}"));
        let why = plan.undo.as_ref().err().cloned();
        let (res, undo) = self.run(plan);
        res.unwrap_or_else(|x| panic!("apply: {x}"));
        undo.unwrap_or_else(|| panic!("an undo, but the plan has none: {why:?}"))
    }

    fn undo(&self, a: UndoAction) -> (Res<String>, Option<UndoAction>) {
        self.l.w.sql_undo(self.db.clone(), a, Vec::new(), false);
        let Msg::SqlAltered { res, undo, .. } = self.l.next() else { panic!("expected SqlAltered") };
        (res, undo)
    }

    /// Everything the structure view reads about the table's columns, indexes and constraints, one line each, so two of
    /// them being equal means the catalogs hold the same table.
    fn shape(&self) -> Vec<String> {
        let st = self.structure();
        let mut v: Vec<String> = st.columns.iter().map(|c| format!("col {}|{}|{}|{:?}|{}|{}", c.name, c.full_type, c.nullable, c.default_raw, c.extra, c.comment)).collect();
        v.extend(st.indexes.iter().map(|i| format!("idx {}|{}|{}|{}", i.name, i.def, i.comment, i.constraint)));
        v.extend(st.constraints.iter().map(|c| format!("con {}|{}|{}", c.name, c.kind, c.def)));
        v
    }

    fn rows(&self) -> String {
        self.one("SELECT string_agg(id::text || ':' || name || ':' || COALESCE(qty::text, '-'), ',' ORDER BY id) FROM t")
    }
}

fn add(def: ColDef) -> Change {
    Change::Add { def, pos: Pos::Keep }
}

fn modify(from: &str, def: ColDef) -> Change {
    Change::Modify { from: from.into(), def, pos: Pos::Keep }
}

fn index(name: &str, kind: IndexKind, cols: &[&str]) -> IndexDef {
    IndexDef { name: name.into(), kind, cols: cols.iter().map(|c| IdxCol { name: (*c).into(), prefix: None, desc: false }).collect(), ..Default::default() }
}

#[test]
fn columns_are_added_renamed_retyped_and_dropped() {
    every_pg(|l, var| {
        let t = fixture(l, var, "cols", TABLE_DDL);
        let mut price = ColDef::new("price", "numeric(10,2)");
        (price.nullable, price.default, price.comment) = (false, Dv::Value("0".into()), "In euros".into());
        t.apply(&[add(price)]);
        let c = t.col("price").unwrap();
        assert_eq!((c.full_type.as_str(), c.nullable, c.default.as_deref(), c.comment.as_str()), ("numeric(10,2)", false, Some("0"), "In euros"), "{var}");
        assert_eq!(t.one("SELECT price::text FROM t WHERE id = 1"), "0.00", "{var}");
        // a rename and a new type together keep the values: qty becomes text through USING
        let mut amount = t.def("qty");
        (amount.name, amount.ty) = ("amount".into(), "text".into());
        t.apply(&[modify("qty", amount)]);
        assert!(t.col("qty").is_none(), "{var}");
        assert_eq!(t.col("amount").unwrap().full_type, "text", "{var}");
        assert_eq!(t.one("SELECT string_agg(id::text || ':' || name || ':' || amount, ',' ORDER BY id) FROM t"), "1:a:1,2:b:2,3:c:30", "{var}");
        // the index that held qty follows the rename
        assert!(t.structure().indexes.iter().find(|i| i.name == "t_name_idx").unwrap().def.contains("amount"), "{var}");
        let mut name = t.def("name");
        name.ty = "character varying(80)".into();
        t.apply(&[modify("name", name)]);
        assert_eq!(t.col("name").unwrap().full_type, "character varying(80)", "{var}");
        // the default that came with the old type survived the retyping
        assert_eq!(t.col("name").unwrap().default.as_deref(), Some("x"), "{var}");
        t.apply(&[Change::Drop("note".into())]);
        assert!(t.col("note").is_none(), "{var}");
    });
}


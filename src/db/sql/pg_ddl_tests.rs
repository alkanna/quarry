//! Live tests of editing a PostgreSQL table's structure, run on every server named by QUARRY_TEST_POSTGRES and
//! QUARRY_TEST_POSTGRES13, and once through the PgBouncer. Each test makes its own schema in the shared `quarry_test`
//! database, so tests of one server run side by side.

use super::ddl::{self, Change, ColDef, Dv, IdxCol, IndexDef, IndexKind, Mode, Pos};
use super::structure::{Column, Structure};
use super::testing::{every_pg, live_pgbouncer, LivePg};
use super::{Db, Dialect};
use crate::db::{Msg, Res, UndoAction};

const TABLE_DDL: &str = "CREATE TABLE t (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name varchar(40) NOT NULL DEFAULT 'x', qty integer, note text); \
                         COMMENT ON COLUMN t.note IS 'free text'; CREATE INDEX t_name_idx ON t (name DESC, qty); \
                         INSERT INTO t (name, qty, note) VALUES ('a', 1, 'one'), ('b', 2, 'two'), ('c', 30, NULL)";

struct T<'a> {
    l: &'a LivePg,
    db: Db,
    pool: sqlx::PgPool,
    schema: String,
}

fn fixture<'a>(l: &'a LivePg, var: &str, tag: &str, ddl: &str) -> T<'a> {
    let db = l.quarry_test();
    let pool = l.fixture_pool();
    let schema = format!("pgddl_{tag}_{}", if var.ends_with("13") { "13" } else { "18" });
    l.qsql(&pool, &format!("DROP SCHEMA IF EXISTS {schema} CASCADE; CREATE SCHEMA {schema}; SET search_path = {schema}; {ddl}"));
    T { l, db, pool, schema }
}

impl Drop for T<'_> {
    fn drop(&mut self) {
        // The pool is gone with the test; a schema left behind by a failed one is dropped by the next run's fixture.
        let _ = self.l.w.rt.block_on(async { sqlx::raw_sql(&format!("DROP SCHEMA IF EXISTS {} CASCADE", self.schema)).execute(&self.pool).await });
    }
}

impl T<'_> {
    fn sql(&self, s: &str) {
        self.l.qsql(&self.pool, &format!("SET search_path = {}; {s}", self.schema));
    }

    fn one(&self, s: &str) -> String {
        self.l.qone(&self.pool, &format!("SET search_path = {}; {s}", self.schema))
    }

    fn structure(&self) -> Structure {
        self.l.w.sql_structure(9, self.db.clone(), self.schema.clone(), "t".into());
        let Msg::SqlStructure { res, .. } = self.l.next() else { panic!("expected SqlStructure") };
        res.unwrap()
    }

    fn col(&self, name: &str) -> Option<Column> {
        self.structure().columns.into_iter().find(|c| c.name == name)
    }

    fn def(&self, name: &str) -> ColDef {
        let st = self.structure();
        ColDef::in_table(&st, st.columns.iter().find(|c| c.name == name).unwrap()).unwrap()
    }

    fn plan(&self, changes: &[Change]) -> Result<ddl::Plan, String> {
        ddl::plan(Dialect::Postgres, &self.db.version, Mode::DEFAULT, "t", &self.structure(), changes)
    }

    fn run(&self, plan: ddl::Plan) -> (Res<String>, Option<UndoAction>) {
        let undo = plan.undo.ok().map(|mut u| {
            u.label = "changed the structure".into();
            u
        });
        self.l.w.pg_alter(1, self.db.clone(), self.schema.clone(), "t".into(), plan.steps, plan.expect.unwrap(), undo, false, "Changed the structure".into());
        let Msg::SqlAltered { res, undo, .. } = self.l.next() else { panic!("expected SqlAltered") };
        (res, undo)
    }

    fn apply(&self, changes: &[Change]) -> UndoAction {
        let (res, undo) = self.run(self.plan(changes).unwrap_or_else(|x| panic!("plan: {x}")));
        res.unwrap_or_else(|x| panic!("apply: {x}"));
        undo.expect("an undo")
    }

    fn undo(&self, a: UndoAction) -> (Res<String>, Option<UndoAction>) {
        self.l.w.sql_undo(self.db.clone(), a, Vec::new(), false);
        let Msg::SqlAltered { res, undo, .. } = self.l.next() else { panic!("expected SqlAltered") };
        (res, undo)
    }

    /// Everything the structure view reads about the table's columns, indexes and constraints, one line each, so two of
    /// them being equal means the catalogs hold the same table.
    fn shape(&self) -> Vec<String> {
        let st = self.structure();
        let mut v: Vec<String> = st.columns.iter().map(|c| format!("col {}|{}|{}|{:?}|{}|{}", c.name, c.full_type, c.nullable, c.default_raw, c.extra, c.comment)).collect();
        v.extend(st.indexes.iter().map(|i| format!("idx {}|{}|{}|{}", i.name, i.def, i.comment, i.constraint)));
        v.extend(st.constraints.iter().map(|c| format!("con {}|{}|{}", c.name, c.kind, c.def)));
        v
    }

    fn rows(&self) -> String {
        self.one("SELECT string_agg(id::text || ':' || name || ':' || COALESCE(qty::text, '-'), ',' ORDER BY id) FROM t")
    }
}

fn add(def: ColDef) -> Change {
    Change::Add { def, pos: Pos::Keep }
}

fn modify(from: &str, def: ColDef) -> Change {
    Change::Modify { from: from.into(), def, pos: Pos::Keep }
}

fn index(name: &str, kind: IndexKind, cols: &[&str]) -> IndexDef {
    IndexDef { name: name.into(), kind, cols: cols.iter().map(|c| IdxCol { name: (*c).into(), prefix: None, desc: false }).collect(), ..Default::default() }
}

#[test]
fn columns_are_added_renamed_retyped_and_dropped() {
    every_pg(|l, var| {
        let t = fixture(l, var, "cols", TABLE_DDL);
        let mut price = ColDef::new("price", "numeric(10,2)");
        (price.nullable, price.default, price.comment) = (false, Dv::Value("0".into()), "In euros".into());
        t.apply(&[add(price)]);
        let c = t.col("price").unwrap();
        assert_eq!((c.full_type.as_str(), c.nullable, c.default.as_deref(), c.comment.as_str()), ("numeric(10,2)", false, Some("0"), "In euros"), "{var}");
        assert_eq!(t.one("SELECT price::text FROM t WHERE id = 1"), "0.00", "{var}");
        // a rename and a new type together keep the values: qty becomes text through USING
        let mut amount = t.def("qty");
        (amount.name, amount.ty) = ("amount".into(), "text".into());
        t.apply(&[modify("qty", amount)]);
        assert!(t.col("qty").is_none(), "{var}");
        assert_eq!(t.col("amount").unwrap().full_type, "text", "{var}");
        assert_eq!(t.one("SELECT string_agg(id::text || ':' || name || ':' || amount, ',' ORDER BY id) FROM t"), "1:a:1,2:b:2,3:c:30", "{var}");
        // the index that held qty follows the rename
        assert!(t.structure().indexes.iter().find(|i| i.name == "t_name_idx").unwrap().def.contains("amount"), "{var}");
        let mut name = t.def("name");
        name.ty = "character varying(80)".into();
        t.apply(&[modify("name", name)]);
        assert_eq!(t.col("name").unwrap().full_type, "character varying(80)", "{var}");
        // the default that came with the old type survived the retyping
        assert_eq!(t.col("name").unwrap().default.as_deref(), Some("x"), "{var}");
        t.apply(&[Change::Drop("note".into())]);
        assert!(t.col("note").is_none(), "{var}");
    });
}

#[test]
fn defaults_nullability_and_comments_change() {
    every_pg(|l, var| {
        let t = fixture(l, var, "dflt", TABLE_DDL);
        let mut qty = t.def("qty");
        (qty.default, qty.nullable, qty.comment) = (Dv::Expr("length('abc')".into()), false, "Never empty".into());
        t.apply(&[modify("qty", qty)]);
        let c = t.col("qty").unwrap();
        assert!(!c.nullable && c.default_expr && c.comment == "Never empty", "{var}");
        assert!(c.default.as_deref().unwrap().starts_with("length("), "{var}");
        let mut name = t.def("name");
        (name.default, name.nullable) = (Dv::Null, true);
        t.apply(&[modify("name", name)]);
        let c = t.col("name").unwrap();
        assert!(c.nullable && c.default.is_none(), "{var}");
        let mut note = t.def("note");
        note.default = Dv::Value("it's".into());
        t.apply(&[modify("note", note)]);
        assert_eq!(t.col("note").unwrap().default.as_deref(), Some("it's"), "{var}");
        t.sql("INSERT INTO t (qty) VALUES (5)");
        assert_eq!(t.one("SELECT note FROM t WHERE qty = 5"), "it's", "{var}");
    });
}

#[test]
fn identity_and_serial_read_as_auto_increment() {
    every_pg(|l, var| {
        let t = fixture(l, var, "auto", "CREATE TABLE t (id serial PRIMARY KEY, n integer, big bigint GENERATED ALWAYS AS IDENTITY, name varchar(40), qty integer, note text)");
        // a serial is an owned sequence in a nextval default, shown as auto increment with that default kept
        let id = t.def("id");
        assert!(id.auto_increment && matches!(&id.default, Dv::Expr(x) if x.starts_with("nextval(")), "{var}");
        let big = t.def("big");
        assert!(big.auto_increment && big.identity_always, "{var}");
        // an identity goes on a plain integer column
        let mut n = t.def("n");
        (n.auto_increment, n.nullable) = (true, false);
        let back = t.apply(&[modify("n", n)]);
        assert!(t.col("n").unwrap().extra.contains("IDENTITY BY DEFAULT"), "{var}");
        t.sql("INSERT INTO t (id) VALUES (default)");
        // undo takes the identity off again and the column is as it was
        let (res, _) = t.undo(back);
        res.unwrap_or_else(|x| panic!("{var}: {x}"));
        assert!(!t.col("n").unwrap().extra.contains("IDENTITY") && t.col("n").unwrap().nullable, "{var}");
        // a new auto increment column is an identity, and a bigint one is too
        let mut seq = ColDef::new("seq", "bigint");
        (seq.auto_increment, seq.nullable) = (true, false);
        t.apply(&[add(seq)]);
        assert!(t.col("seq").unwrap().extra.contains("IDENTITY BY DEFAULT"), "{var}");
        // dropping the serial's auto increment leaves a plain column, and undo puts the same nextval default back
        let mut plain = t.def("id");
        (plain.auto_increment, plain.default) = (false, Dv::None);
        let before = t.shape();
        let a = t.apply(&[modify("id", plain)]);
        assert!(!t.col("id").unwrap().extra.contains("auto_increment"), "{var}");
        t.undo(a).0.unwrap();
        assert_eq!(t.shape(), before, "{var}");
        // a text column cannot be an identity
        let mut s = t.def("note");
        (s.auto_increment, s.nullable) = (true, false);
        assert!(t.plan(&[modify("note", s)]).unwrap_err().contains("smallint, integer or bigint"), "{var}");
    });
}

#[test]
fn indexes_and_constraints_are_made_renamed_and_dropped() {
    every_pg(|l, var| {
        let t = fixture(l, var, "idx", TABLE_DDL);
        let mut by_note = index("t_note_uq", IndexKind::Unique, &["note"]);
        by_note.comment = "one note each".into();
        by_note.cols[0].desc = true;
        t.apply(&[Change::AddIndex(by_note)]);
        let ix = t.structure().indexes.into_iter().find(|i| i.name == "t_note_uq").unwrap();
        assert!(ix.unique && ix.def.contains("(note DESC)") && ix.comment == "one note each" && !ix.constraint, "{var}");
        // index names belong to the schema, so a rename and a drop name it with its schema
        let st = t.structure();
        let old = IndexDef::from_index(st.indexes.iter().find(|i| i.name == "t_name_idx").unwrap());
        t.apply(&[Change::RenameIndex { from: "t_name_idx".into(), to: "t_by_name".into(), def: old }]);
        assert!(t.structure().indexes.iter().any(|i| i.name == "t_by_name"), "{var}");
        t.apply(&[Change::DropIndex("t_by_name".into())]);
        assert!(t.structure().indexes.iter().all(|i| i.name != "t_by_name"), "{var}");
        // the primary key is a constraint: it is dropped and renamed as one
        let pk = t.structure().indexes.iter().find(|i| i.primary).unwrap().name.clone();
        assert_eq!(pk, "t_pkey", "{var}");
        t.apply(&[Change::RenameIndex { from: pk.clone(), to: "t_key".into(), def: IndexDef::from_index(&t.structure().indexes[0]) }]);
        assert_eq!(t.structure().constraints.iter().find(|c| c.kind == 'p').unwrap().name, "t_key", "{var}");
        t.apply(&[Change::DropIndex("t_key".into())]);
        assert!(t.structure().constraints.iter().all(|c| c.kind != 'p'), "{var}");
        // a new primary key makes its column NOT NULL
        t.apply(&[Change::AddIndex(index("t_pk2", IndexKind::Primary, &["name", "id"]))]);
        let st = t.structure();
        assert!(st.indexes.iter().any(|i| i.primary && i.name == "t_pk2" && i.cols.len() == 2), "{var}");
        // an index the editor cannot write back is refused instead of being dropped for good
        t.sql("CREATE INDEX t_partial ON t (qty) WHERE qty > 1");
        let err = t.plan(&[Change::DropIndex("t_partial".into())]).unwrap().undo.unwrap_err();
        assert!(err.contains("cannot be read back"), "{var}: {err}");
        assert!(t.plan(&[Change::AddIndex(IndexDef::from_index(&t.structure().indexes.iter().find(|i| i.name == "t_partial").unwrap().clone()))]).unwrap_err().contains("cannot write"), "{var}");
    });
}

#[test]
fn undo_restores_the_exact_structure() {
    every_pg(|l, var| {
        let t = fixture(l, var, "undo", TABLE_DDL);
        let before = t.shape();
        let mut price = ColDef::new("price", "numeric(10,2)");
        (price.nullable, price.default) = (false, Dv::Value("1".into()));
        let mut qty = t.def("qty");
        (qty.name, qty.ty, qty.comment, qty.default) = ("amount".into(), "bigint".into(), "How many".into(), Dv::Value("7".into()));
        let mut name = t.def("name");
        (name.nullable, name.default) = (true, Dv::Null);
        let mut note = t.def("note");
        note.comment = String::new();
        let cases: Vec<(&str, Vec<Change>)> = vec![
            ("add a column", vec![add(price)]),
            ("rename, retype, default and comment", vec![modify("qty", qty)]),
            ("nullability and default", vec![modify("name", name)]),
            ("remove a comment", vec![modify("note", note)]),
            ("add and drop an index", vec![Change::AddIndex(index("t_note_ix", IndexKind::Index, &["note"])), Change::DropIndex("t_name_idx".into())]),
            ("drop and add the primary key", vec![Change::DropIndex("t_pkey".into()), Change::AddIndex(index("t_pk3", IndexKind::Primary, &["id"]))]),
            ("several at once", vec![add(ColDef::new("extra", "jsonb")), Change::Drop("qty".into())]),
        ];
        for (what, changes) in cases {
            let a = t.apply(&changes);
            assert_ne!(t.shape(), before, "{var}: {what} changed nothing");
            let (res, again) = t.undo(a);
            res.unwrap_or_else(|x| panic!("{var}: undo of {what}: {x}"));
            assert!(again.is_none(), "{var}: {what}");
            let mut want = before.clone();
            let mut got = t.shape();
            // a dropped column comes back last: PostgreSQL has no column order to put it in
            if what == "several at once" {
                want.sort();
                got.sort();
            }
            assert_eq!(got, want, "{var}: undo of {what}");
        }
        // a primary key on a nullable column: undo drops it and the column may be NULL again
        // the case before dropped qty and its values with it, and a key needs a value in every row
        t.sql("UPDATE t SET qty = id");
        let a = t.apply(&[Change::DropIndex("t_pkey".into()), Change::AddIndex(index("t_note_pk", IndexKind::Primary, &["qty"]))]);
        assert!(!t.col("qty").unwrap().nullable, "{var}");
        t.sql("ALTER TABLE t DROP CONSTRAINT t_note_pk");
        let kept = t.shape();
        // the table changed since, so the undo is refused and nothing runs
        let (res, kept_undo) = t.undo(a);
        assert!(res.unwrap_err().contains("Undo refused"), "{var}");
        assert!(kept_undo.is_some(), "{var}");
        assert_eq!(t.shape(), kept, "{var}");
    });
}

#[test]
fn a_changed_table_refuses_the_plan_and_nothing_runs() {
    every_pg(|l, var| {
        let t = fixture(l, var, "stale", TABLE_DDL);
        let plan = t.plan(&[add(ColDef::new("extra", "text")), modify("note", { let mut d = t.def("note"); d.ty = "varchar(9)".into(); d })]).unwrap();
        let before = t.shape();
        // another session changes a column the plan touches, after the plan was made
        t.sql("ALTER TABLE t ALTER COLUMN note SET DEFAULT 'later'");
        let changed = t.shape();
        let (res, undo) = t.run(plan);
        let err = res.unwrap_err();
        assert!(err.contains("changed since this plan was made") && err.contains("column note"), "{var}: {err}");
        assert!(undo.is_none(), "{var}");
        assert_eq!(t.shape(), changed, "{var}");
        assert_ne!(changed, before, "{var}");
        assert!(t.col("extra").is_none(), "{var}");
        // another session adds the column the plan was about to add
        let plan = t.plan(&[add(ColDef::new("extra", "text"))]).unwrap();
        t.sql("ALTER TABLE t ADD COLUMN extra integer");
        let (res, _) = t.run(plan);
        assert!(res.unwrap_err().contains("column extra"), "{var}");
        assert_eq!(t.col("extra").unwrap().full_type, "integer", "{var}");
    });
}

#[test]
fn a_held_lock_fails_the_plan_on_the_lock_timeout() {
    every_pg(|l, var| {
        let t = fixture(l, var, "lock", TABLE_DDL);
        let plan = t.plan(&[add(ColDef::new("extra", "text"))]).unwrap();
        let before = t.shape();
        // another session holds the table until the test lets go
        let tx = l.w.rt.block_on(async {
            let mut tx = t.pool.begin().await.unwrap();
            sqlx::raw_sql(&format!("LOCK TABLE {}.t IN ACCESS SHARE MODE", t.schema)).execute(&mut *tx).await.unwrap();
            tx
        });
        let started = std::time::Instant::now();
        let (res, undo) = t.run(plan);
        let err = res.unwrap_err();
        assert!(err.contains("locked by another session") && err.contains("Nothing was changed"), "{var}: {err}");
        assert!(undo.is_none() && started.elapsed() < std::time::Duration::from_secs(8), "{var}: {:?}", started.elapsed());
        l.w.rt.block_on(async { tx.rollback().await.ok() });
        assert_eq!(t.shape(), before, "{var}");
        // with the lock gone the same plan runs
        let (res, _) = t.run(t.plan(&[add(ColDef::new("extra", "text"))]).unwrap());
        res.unwrap_or_else(|x| panic!("{var}: {x}"));
        assert!(t.col("extra").is_some(), "{var}");
    });
}

#[test]
fn a_failing_statement_rolls_back_the_statements_before_it() {
    every_pg(|l, var| {
        let t = fixture(l, var, "fail", TABLE_DDL);
        let before = t.shape();
        // the third change is valid text but not a type, so the server refuses it after two statements ran
        let plan = t.plan(&[add(ColDef::new("first", "integer")), Change::Drop("note".into()), add(ColDef::new("third", "nosuchtype"))]).unwrap();
        assert_eq!(plan.steps.len(), 3);
        let (res, undo) = t.run(plan);
        let err = res.unwrap_err();
        assert!(err.contains("nosuchtype") && err.contains("statement 3 of 3") && err.contains("rolled back"), "{var}: {err}");
        assert!(undo.is_none(), "{var}");
        assert_eq!(t.shape(), before, "{var}");
        assert_eq!(t.rows(), "1:a:1,2:b:2,3:c:30", "{var}");
        // a conversion the data cannot take fails the same way
        let mut note = t.def("note");
        note.ty = "integer".into();
        let (res, _) = t.run(t.plan(&[add(ColDef::new("again", "integer")), modify("note", note)]).unwrap());
        assert!(res.unwrap_err().contains("statement 2 of 2"), "{var}");
        assert_eq!(t.shape(), before, "{var}");
    });
}

#[test]
fn text_that_carries_a_second_statement_is_refused_before_anything_runs() {
    every_pg(|l, var| {
        let t = fixture(l, var, "evil", TABLE_DDL);
        let before = t.shape();
        for ty in ["integer; DROP TABLE t", "integer) , ADD COLUMN z int", "integer -- x", "integer /* x */", "'a'"] {
            let err = t.plan(&[add(ColDef::new("x", ty))]).unwrap_err();
            assert!(err.contains("type"), "{var}: {ty}: {err}");
        }
        for expr in ["1; DROP TABLE t", "1) , ADD COLUMN z int DEFAULT (2", "1 -- x", "1 /* x */", "'open", "$$ open"] {
            let mut d = ColDef::new("x", "integer");
            d.default = Dv::Expr(expr.into());
            let err = t.plan(&[add(d)]).unwrap_err();
            assert!(err.contains("default expression"), "{var}: {expr}: {err}");
        }
        // a dollar quote and a quoted value are strings, not statements
        let mut d = ColDef::new("x", "text");
        d.default = Dv::Expr("$q$; DROP TABLE t; --$q$".into());
        t.apply(&[add(d)]);
        assert_eq!(t.col("x").unwrap().default.as_deref(), Some("; DROP TABLE t; --"), "{var}");
        let mut v = ColDef::new("y", "text");
        v.default = Dv::Value("'; DROP TABLE t; --".into());
        t.apply(&[add(v)]);
        assert_eq!(t.one("SELECT count(*)::text FROM t"), "3", "{var}");
        assert_ne!(t.shape(), before, "{var}");
        // a staged position or a foreign key is refused, not written wrong
        assert!(t.plan(&[Change::Add { def: ColDef::new("z", "integer"), pos: Pos::First }]).unwrap_err().contains("cannot place"), "{var}");
    });
}

#[test]
fn one_apply_and_its_undo_through_a_pooler() {
    let Some(l) = live_pgbouncer() else { return };
    let t = fixture(&l, "QUARRY_TEST_PGBOUNCER", "pgb", TABLE_DDL);
    assert!(t.db.pooler());
    let before = t.shape();
    let mut qty = t.def("qty");
    (qty.name, qty.ty) = ("amount".into(), "bigint".into());
    let a = t.apply(&[add(ColDef::new("extra", "text")), modify("qty", qty), Change::AddIndex(index("t_note_pb", IndexKind::Index, &["note"]))]);
    assert!(t.col("extra").is_some() && t.col("amount").is_some(), "applied");
    let (res, _) = t.undo(a);
    res.unwrap_or_else(|x| panic!("undo: {x}"));
    assert_eq!(t.shape(), before);
    assert_eq!(t.rows(), "1:a:1,2:b:2,3:c:30");
    // the settings of the transaction never reached the session of another client of the pooler
    assert_eq!(t.one("SHOW lock_timeout"), "0");
}
